#!/usr/bin/env python3
"""
Day 1 — Read dataset columns and build feature understanding report.

Usage:
  python datasets/scripts/inspect_datasets.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

try:
    import pandas as pd
except ImportError:
    print("Install pandas: pip install pandas")
    sys.exit(1)

REPO_ROOT = Path(__file__).resolve().parents[2]
ROOT = REPO_ROOT / "datasets"
RAW = ROOT / "raw"
PROCESSED = ROOT / "processed"
UCI_DIR = RAW / "student_performance"
OULAD_DIR = RAW / "oulad"

# Columns we care about for Student Performance Prediction
PRODUCT_FEATURES = {
    "study_hours": "Time spent studying per week",
    "attendance": "Class attendance / engagement",
    "sleep": "Sleep hours (wellness factor)",
    "assignments": "Assignments completed / failed",
    "marks": "Exam or course grades (target)",
}

UCI_COLUMN_MAP = {
    "studytime": "study_hours (1=very low … 4=very high)",
    "absences": "attendance (inverse — more absences = lower attendance)",
    "failures": "assignments (past class failures)",
    "G1": "marks (first period grade, 0–20)",
    "G2": "marks (second period grade, 0–20)",
    "G3": "marks (final grade, 0–20) — primary target",
    "activities": "assignments (extra-curricular participation)",
    "higher": "wants higher education (motivation)",
    "internet": "internet access at home",
    "health": "self-reported health (related to sleep/wellness)",
}

OULAD_KEY_FILES = {
    "studentInfo.csv": ["id_student", "code_module", "final_result", "num_of_prev_attempts"],
    "studentAssessment.csv": ["id_student", "id_assessment", "score", "date_submitted"],
    "assessments.csv": ["id_assessment", "assessment_type", "date", "weight"],
    "studentVle.csv": ["id_student", "sum_click", "date"],
}


def inspect_csv(path: Path) -> dict:
    df = pd.read_csv(path, sep=";" if path.suffix == ".csv" and "student" in path.name else ",")
    return {
        "file": str(path.relative_to(ROOT)),
        "rows": int(len(df)),
        "columns": list(df.columns),
        "dtypes": {c: str(df[c].dtype) for c in df.columns},
        "sample": df.head(3).to_dict(orient="records"),
        "null_counts": {c: int(df[c].isna().sum()) for c in df.columns},
    }


def inspect_uci() -> list[dict]:
    results = []
    if not UCI_DIR.exists():
        return results
    for csv in sorted(UCI_DIR.glob("*.csv")):
        results.append(inspect_csv(csv))
    return results


def inspect_oulad() -> list[dict]:
    results = []
    if not OULAD_DIR.exists():
        return results
    for csv in sorted(OULAD_DIR.glob("*.csv")):
        try:
            results.append(inspect_csv(csv))
        except Exception as exc:
            results.append({"file": str(csv.name), "error": str(exc)})
    return results


def write_markdown_report(inventory: dict, out_path: Path) -> None:
    lines = [
        "# Dataset columns report (Day 1)",
        "",
        "Generated by `datasets/scripts/inspect_datasets.py`.",
        "",
        "## Product features (target schema)",
        "",
        "| Feature | Description |",
        "|---------|-------------|",
    ]
    for k, v in PRODUCT_FEATURES.items():
        lines.append(f"| `{k}` | {v} |")

    lines.extend(["", "## A — UCI Student Performance", ""])
    uci = inventory.get("uci_student_performance", [])
    if not uci:
        lines.append("_Not downloaded. Run `download_datasets.py`._")
    else:
        for ds in uci:
            lines.append(f"### `{ds['file']}` ({ds['rows']} rows)")
            lines.append("")
            lines.append("| Column | Type | Nulls | Maps to |")
            lines.append("|--------|------|-------|---------|")
            for col in ds["columns"]:
                mapped = UCI_COLUMN_MAP.get(col, "—")
                nulls = ds["null_counts"].get(col, 0)
                dtype = ds["dtypes"].get(col, "?")
                lines.append(f"| `{col}` | {dtype} | {nulls} | {mapped} |")
            lines.append("")

    lines.extend(["", "## B — OULAD", ""])
    oulad = inventory.get("oulad", [])
    if not oulad:
        lines.append("_No CSV files in `raw/oulad/`. See DOWNLOAD_INSTRUCTIONS.txt._")
    else:
        for ds in oulad:
            if "error" in ds:
                lines.append(f"- **{ds['file']}**: error — {ds['error']}")
                continue
            lines.append(f"### `{ds['file']}` ({ds['rows']} rows, {len(ds['columns'])} columns)")
            lines.append("")
            key = OULAD_KEY_FILES.get(Path(ds["file"]).name, [])
            if key:
                lines.append(f"Key columns: `{', '.join(key)}`")
            lines.append("")

    lines.extend(
        [
            "",
            "## Notes",
            "",
            "- **Sleep** is not in UCI; consider survey data or `health` as a weak proxy.",
            "- **OULAD** is best for engagement + dropout; merge with UCI for richer models later.",
            "- Next (Day 2+): clean → `processed/` → feature engineering → `final/`.",
            "",
        ]
    )
    out_path.write_text("\n".join(lines))


def main() -> int:
    PROCESSED.mkdir(parents=True, exist_ok=True)
    (ROOT / "final").mkdir(parents=True, exist_ok=True)

    print("=== Day 1: Inspect datasets ===\n")

    inventory = {
        "uci_student_performance": inspect_uci(),
        "oulad": inspect_oulad(),
        "product_features": PRODUCT_FEATURES,
        "uci_column_map": UCI_COLUMN_MAP,
    }

    json_path = PROCESSED / "columns_inventory.json"
    json_path.write_text(json.dumps(inventory, indent=2, default=str))
    print(f"[OK] {json_path}")

    md_path = PROCESSED / "dataset_columns_report.md"
    write_markdown_report(inventory, md_path)
    print(f"[OK] {md_path}")

    uci_count = len(inventory["uci_student_performance"])
    oulad_count = len(inventory["oulad"])
    print(f"\nSummary: UCI files={uci_count}, OULAD files={oulad_count}")

    if uci_count:
        first = inventory["uci_student_performance"][0]
        print(f"\nUCI columns ({first['file']}):")
        print(f"  {', '.join(first['columns'][:12])}...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
